export const filterSpecializations = (query: string, limit = 12): string[] => {
  const q = query.trim().toLowerCase();
  if (!q) return MEDICAL_SPECIALIZATIONS.slice(0, limit);
  return MEDICAL_SPECIALIZATIONS.filter((item) => item.toLowerCase().includes(q)).slice(0, limit);
};
